	<h2>Storage outside your country</h2>
	<p>
		FreeSpeech is hosted in the United States. If you are in Australia, New Zealand or elsewhere
		outside the USA, your information is sent to and stored in the United States, and is handled by
		the services listed above. I will give advance notice before moving hosting, or anyone with
		access to your data, to another country.
	</p>
	<h2>Security</h2>
	<p>I protect your information by:</p>
	<ul>
		<li>encrypting connections with HTTPS</li>
		<li>hashing passwords with bcrypt</li>
		<li>storing ElevenLabs keys encrypted</li>
		<li>limiting administrative access to the servers to named, trusted people</li>
		<li>limiting each account&#39;s data to that account</li>
	</ul>
	<p>No system is perfectly secure. Please use a strong password.</p>
	<h2>How long I keep information</h2>
	<ul>
		<li>
			<strong>Account, boards and images:</strong> kept while your account exists. Deleted when you delete
			your account, or when you ask me to delete them.
		</li>
		<li>
			<strong>Deleted data in backups:</strong> database backups are kept for up to 7 days, so deleted
			data is gone from backups within that time.
		</li>
		<li><strong>Server logs:</strong> about 14 days.</li>
		<li><strong>Password-reset links:</strong> expire after one hour.</li>
		<li>
			<strong>Inactive accounts:</strong> kept until you delete them or ask me to. I don&#39;t delete
			inactive accounts automatically.
		</li>
	</ul>
	<h2>Your rights and choices</h2>
	<ul>
		<li>
			<strong>Access and export:</strong> download all your data as a JSON file on your Profile page.
		</li>
		<li>
			<strong>Correction:</strong> edit your account and boards at any time, or ask me to correct something.
		</li>
		<li>
			<strong>Deletion:</strong> delete your account on your Profile page. This removes your account,
			boards and uploaded images.
		</li>
		<li>
			<strong>Requests:</strong> email
			<a href="mailto:archercalder@gmail.com">archercalder@gmail.com</a>.
			<ul>
				<li>Requests are free and I&#39;ll respond within 30 days.</li>
				<li>I may need to confirm you own the account.</li>
				<li>
					Parents, and schools that authorized use, can ask to review or delete a child&#39;s
					information.
				</li>
			</ul>
		</li>
	</ul>
