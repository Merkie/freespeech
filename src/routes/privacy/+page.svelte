	<h1>FreeSpeech AAC Privacy Policy</h1>
	<p><strong>Version 2026-09-29 · Effective 29 September 2026</strong></p>
	<p>
		FreeSpeech AAC (freespeechaac.com) is a free augmentative and alternative communication (AAC)
		web app. It is run by <strong>Archer Calder</strong>, an individual developer in Houston, Texas,
		USA. I am responsible for your information and act as the privacy officer. Contact:
		<strong><a href="mailto:archercalder@gmail.com">archercalder@gmail.com</a></strong>.
	</p>
	<h2>Who uses FreeSpeech</h2>
	<p>
		Accounts are for adults: parents and caregivers, teachers, speech-language pathologists,
		schools, and adult AAC users. Children and other people may use boards that an account holder
		sets up, but children should not create their own accounts. If you set up FreeSpeech for a
		child, you confirm that you are their parent or guardian, or that you have the parent&#39;s or
		school&#39;s authorization.
	</p>
	<p>
		<strong>Schools.</strong> A school may consent on parents&#39; behalf for educational use. In that
		case I use students&#39; information only to provide FreeSpeech to the school, and for no other commercial
		purpose. On request, a school can get a description of the information held, review it, have it deleted,
		and stop further collection.
	</p>
	<h2>What I collect</h2>
	<p><strong>Account information</strong></p>
	<ul>
		<li>Email address and name.</li>
		<li>
			A password, stored only as a bcrypt hash. If you use Google sign-in, I receive your name,
			email address and profile picture from Google and do not need a password.
		</li>
		<li>An optional profile image.</li>
	</ul>
	<p><strong>Boards and content</strong></p>
	<ul>
		<li>Boards, pages and tiles, including their text and images.</li>
		<li>Images you upload.</li>
		<li>
			This content can include a child&#39;s personal vocabulary, names and photos, and can reveal
			disability or health information. I treat it as sensitive and use it only to run the service
			for you.
		</li>
	</ul>
	<p><strong>ElevenLabs API key (optional)</strong></p>
	<ul>
		<li>If you add your own ElevenLabs key, I store it encrypted.</li>
	</ul>
	<p><strong>Server logs</strong></p>
	<ul>
		<li>
			The web server&#39;s access logs record IP addresses and requested addresses, including image
			search terms. They are kept for about 14 days.
		</li>
		<li>Application logs record only the request method and path.</li>
	</ul>
	<p><strong>Settings kept only on your device</strong></p>
	<ul>
		<li>
			Voice, PIN, behavior settings and offline copies of boards are stored in your browser&#39;s
			storage and are not sent to me.
		</li>
		<li>Clearing your browser&#39;s site data removes them.</li>
		<li>The PIN is a convenience lock, not strong security.</li>
	</ul>
	<p>
		You need an email address and either a password or Google sign-in to create an account.
		Everything else is optional.
	</p>
	<h2>How information is collected</h2>
	<ul>
		<li>Directly from you when you create an account and build boards.</li>
		<li>From Google, if you choose Google sign-in.</li>
		<li>Automatically in server logs when your browser contacts FreeSpeech.</li>
	</ul>
	<h2>How I use it</h2>
	<p>I use your information to:</p>
	<ul>
		<li>sign you in and keep your account secure</li>
		<li>store, sync and show your boards</li>
		<li>send password-reset emails</li>
		<li>turn text into speech when you enable cloud voices</li>
		<li>search for symbols and images</li>
		<li>remove image backgrounds when you ask</li>
		<li>fix problems and protect against abuse</li>
		<li>answer your requests, and tell you about changes or security incidents</li>
	</ul>
	<p>I do <strong>not</strong>:</p>
	<ul>
		<li>use analytics or advertising</li>
		<li>sell data or share it for marketing</li>
		<li>send marketing email</li>
		<li>build profiles</li>
		<li>use your information to train AI or language models</li>
	</ul>
